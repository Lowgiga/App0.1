#!/usr/bin/env python3
"""Generate and check the plan-vs-actual inventory from the acceptance matrix.

The matrix (docs/16-acceptance-matrix.md) is the single source of truth for the
status of every requirement. A hand-copied inventory goes stale, so this tool
parses the matrix with a CommonMark/GFM parser (no line regexes) and renders
the inventory block between two markers in a target document.

    python tools/repo/requirements_inventory.py                  # print block
    python tools/repo/requirements_inventory.py --write docs/37-bestandsaufnahme.md
    python tools/repo/requirements_inventory.py --check docs/37-bestandsaufnahme.md

Exit codes: 0 ok; 1 target stale, unreadable, unwritable or without exactly one
pair of markers; 2 matrix unusable or invalid arguments (argparse also uses 2).
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from markdown_it import MarkdownIt
from markdown_it.token import Token

# Same extensions as the link checker; GitHub renders both.
PARSER = MarkdownIt('commonmark').enable(['table', 'strikethrough'])
REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MATRIX = REPO_ROOT / 'docs' / '16-acceptance-matrix.md'
START = '<!-- inventory:start (generated by tools/repo/requirements_inventory.py, do not edit) -->'
END = '<!-- inventory:end -->'
ID_PATTERN = re.compile(r'^[A-Z]{2,6}-\d{2}$')
HEADING_COUNT = re.compile(r'\b(\d+)\b')
ID_HEADER = 'ID'
STATUS_COLUMN = 1
NEXT_STEP_COLUMN = 2
NONE = 'keine'
# Characters that open inline constructs in CommonMark or on GitHub (tables, strikethrough,
# math); escaping ASCII punctuation is always allowed (CommonMark 0.31.2, section 2.4).
MARKDOWN_SPECIAL = re.compile(r'([\\`*_\[\]<&|~$])')
BACKTICK_RUN = re.compile(r'`+')
WHITESPACE = re.compile(r'\s+')

# The first matching prefix of the bold label wins, so a combined label such as
# "Implementiert und Suite-geprüft" counts as "Implementiert" (the conservative reading).
STATUS_CLASSES: tuple[tuple[str, str], ...] = (
    ('teilweise geprüft', 'Teilweise geprüft'),
    ('geprüft', 'Geprüft'),
    ('implementiert', 'Implementiert'),
    ('vorbereitet', 'Vorbereitet'),
    ('offen', 'Offen'),
)
CLASS_ORDER = [label for _, label in STATUS_CLASSES]


class MatrixError(ValueError):
    """The matrix cannot be turned into a trustworthy inventory."""


@dataclass(frozen=True)
class Requirement:
    rid: str
    status: str  # plain text of the bold label
    status_class: str
    next_step: str  # Markdown, safe to place in a GFM table cell


def escape(text: str) -> str:
    """Escape text so that it renders literally inside a GFM table cell."""
    return MARKDOWN_SPECIAL.sub(r'\\\1', text)


def code_span(content: str) -> str:
    """A code span holding `content`; the fence is longer than any backtick run inside."""
    fence = '`' * (max((len(run) for run in BACKTICK_RUN.findall(content)), default=0) + 1)
    pad = ' ' if content.startswith('`') or content.endswith('`') else ''
    # GFM splits cells on '|' even inside code spans unless the pipe is escaped.
    return f'{fence}{pad}{content.replace("|", chr(92) + "|")}{pad}{fence}'


def _visible(children: list[Token], markdown: bool) -> str:
    """Visible text: whitespace runs in prose collapse to one space, code spans stay verbatim."""
    segments: list[tuple[str, str]] = []
    for child in children:
        if child.type == 'text':
            if segments and segments[-1][0] == 'text':
                segments[-1] = ('text', segments[-1][1] + child.content)
            else:
                segments.append(('text', child.content))
        elif child.type == 'code_inline':
            segments.append(('code', child.content))
    parts = []
    for index, (kind, value) in enumerate(segments):
        if kind == 'code':
            parts.append(code_span(value) if markdown else value)
            continue
        # GFM table cells are single-line, so no soft or hard breaks can occur here.
        text = WHITESPACE.sub(' ', value)
        if index == 0:
            text = text.lstrip()
        if index == len(segments) - 1:
            text = text.rstrip()
        parts.append(escape(text) if markdown else text)
    return ''.join(parts)


def plain_text(inline: Token) -> str:
    """Visible text of an inline token: text and code spans, markup and link targets dropped."""
    return _visible(inline.children or [], markdown=False)


def cell_markdown(inline: Token) -> str:
    """Like plain_text, but escaped for a table cell and with code spans kept as code."""
    return _visible(inline.children or [], markdown=True)


def leading_status(inline: Token) -> str:
    """The bold label that opens a cell, e.g. '**Geprüft (Web):** …' -> 'Geprüft (Web)'."""
    # markdown-it emits an empty text token before a leading delimiter run; skip it.
    children = [c for c in inline.children or [] if not (c.type == 'text' and c.content == '')]
    if not children or children[0].type != 'strong_open':
        raise MatrixError(f'cell does not start with a bold status: {inline.content[:60]!r}')
    # markdown-it always emits a matching strong_close after a strong_open.
    end = next(i for i, child in enumerate(children) if child.type == 'strong_close')
    return _visible(children[1:end], markdown=False).rstrip(':').strip()


def classify(status: str) -> str:
    lowered = status.casefold()
    for prefix, label in STATUS_CLASSES:
        if lowered.startswith(prefix):
            return label
    raise MatrixError(f'unknown status {status!r}; extend STATUS_CLASSES deliberately')


def _table(tokens: list[Token], start: int) -> tuple[list[Token], list[list[Token]]]:
    """Header cells and body rows (inline token per cell) of the table opened at `start`."""
    header: list[Token] = []
    rows: list[list[Token]] = []
    row: list[Token] = []
    in_body = False
    i = start
    while tokens[i].type != 'table_close':
        kind = tokens[i].type
        if kind == 'tbody_open':
            in_body = True
        elif kind == 'tr_open':
            row = []
        elif kind == 'inline':
            row.append(tokens[i])
        elif kind == 'tr_close':
            if in_body:
                rows.append(row)
            else:
                header = row
        i += 1
    return header, rows


def parse_matrix(text: str) -> tuple[int, list[Requirement]]:
    """Return (declared count, requirements) of the table under the 'Die N Anforderungen' heading."""
    # NFC first: files saved on macOS may store umlauts decomposed (NFD).
    tokens = PARSER.parse(unicodedata.normalize('NFC', text))
    declared: int | None = None
    for i, token in enumerate(tokens):
        if token.type == 'heading_open' and token.tag == 'h2':
            title = tokens[i + 1].content
            match = HEADING_COUNT.search(title)
            declared = int(match.group(1)) if match and 'Anforderungen' in title else None
            continue
        if token.type == 'table_open' and declared is not None:
            header, rows = _table(tokens, i)
            return declared, _requirements(header, rows, declared)
    raise MatrixError("no table under a heading like '## Die 27 Anforderungen'")


def _requirements(header: list[Token], rows: list[list[Token]], declared: int) -> list[Requirement]:
    # GFM pads or truncates every row to the header's column count, so checking the header
    # once guarantees that every row has the status and next-step cells.
    if len(header) <= NEXT_STEP_COLUMN or plain_text(header[0]) != ID_HEADER:
        raise MatrixError(f'requirements table needs at least {NEXT_STEP_COLUMN + 1} columns, the first named ID')
    result: list[Requirement] = []
    for cells in rows:
        rid = plain_text(cells[0])
        if not ID_PATTERN.match(rid):
            raise MatrixError(f'invalid requirement id {rid!r}')
        status = leading_status(cells[STATUS_COLUMN])
        next_step = cell_markdown(cells[NEXT_STEP_COLUMN])
        if not next_step:
            raise MatrixError(f'{rid}: empty next step')
        result.append(Requirement(rid, status, classify(status), next_step))
    duplicates = sorted(rid for rid, n in Counter(r.rid for r in result).items() if n > 1)
    if duplicates:
        raise MatrixError(f'duplicate ids: {", ".join(duplicates)}')
    if len(result) != declared:
        raise MatrixError(f'heading declares {declared} requirements, table has {len(result)}')
    return result


def render(requirements: list[Requirement]) -> str:
    counts = Counter(r.status_class for r in requirements)
    lines = [
        START,
        '',
        f'Quelle: Anforderungsmatrix (docs/16), {len(requirements)} Anforderungen.',
        '',
        '| Statusklasse | Anzahl | IDs |',
        '| --- | ---: | --- |',
    ]
    for label in CLASS_ORDER:
        ids = [r.rid for r in requirements if r.status_class == label]
        lines.append(f'| {label} | {counts[label]} | {", ".join(ids) or NONE} |')
    lines += [
        f'| **Summe** | **{len(requirements)}** | |',
        '',
        '| ID | Status laut Matrix | Kleinster offener Schritt laut Matrix |',
        '| --- | --- | --- |',
    ]
    lines += [f'| {r.rid} | {escape(r.status)} | {r.next_step} |' for r in requirements]
    lines += ['', END]
    return '\n'.join(lines)


def splice(document: str, block: str) -> str:
    if document.count(START) != 1 or document.count(END) != 1:
        raise ValueError('expected exactly one start and one end marker')
    start, end = document.find(START), document.find(END)
    if end < start:
        raise ValueError('end marker before start marker')
    return document[:start] + block + document[end + len(END) :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--matrix', type=Path, default=DEFAULT_MATRIX)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', type=Path, metavar='DOC', help='replace the marked block in DOC')
    mode.add_argument('--check', type=Path, metavar='DOC', help='fail if the marked block in DOC is stale')
    args = parser.parse_args(argv)
    try:
        _, requirements = parse_matrix(args.matrix.read_text(encoding='utf-8'))
    except (OSError, UnicodeDecodeError, MatrixError) as error:
        print(f'matrix unusable: {error}', file=sys.stderr)
        return 2
    block = render(requirements)
    target = args.write or args.check
    if target is None:
        print(block)
        return 0
    try:
        current = target.read_text(encoding='utf-8')
        updated = splice(current, block)
        if args.write and updated != current:
            target.write_text(updated, encoding='utf-8')
    except (OSError, UnicodeDecodeError, ValueError) as error:
        print(f'{target}: {error}', file=sys.stderr)
        return 1
    if args.write:
        print(f'{target}: inventory written ({len(requirements)} requirements)')
        return 0
    if updated != current:
        print(f'{target}: inventory is stale; run with --write {target}', file=sys.stderr)
        return 1
    print(f'{target}: inventory up to date ({len(requirements)} requirements)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
